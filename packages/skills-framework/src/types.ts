/**
 * Skills Framework Type Definitions
 *
 * Types for the progressive capability loading and custom skill system.
 *
 * @see https://github.com/anthropics/claude-cookbooks/tree/main/skills
 */

/**
 * Skill metadata from SKILL.md frontmatter
 */
export interface SkillMetadata {
  /** Unique skill identifier */
  name: string;

  /** Human-readable skill name */
  displayName: string;

  /** Skill description */
  description: string;

  /** Skill version */
  version: string;

  /** Author or organization */
  author?: string;

  /** Skill category */
  category?: SkillCategory;

  /** Tags for discovery */
  tags?: string[];

  /** Required dependencies */
  dependencies?: string[];

  /** Required tools/capabilities */
  requiredTools?: string[];

  /** Minimum model version required */
  minModelVersion?: string;

  /** Whether the skill is experimental */
  experimental?: boolean;
}

/**
 * Skill categories
 */
export type SkillCategory =
  | 'document-generation'  // Excel, PowerPoint, PDF, Word
  | 'data-analysis'        // Analytics, visualization
  | 'automation'           // Workflow automation
  | 'integration'          // External system integration
  | 'research'             // Research and analysis
  | 'communication'        // Email, messaging
  | 'development'          // Code generation, review
  | 'custom';              // User-defined

/**
 * Skill file structure
 */
export interface SkillStructure {
  /** Path to SKILL.md (required) */
  skillMdPath: string;

  /** Optional scripts directory */
  scriptsPath?: string;

  /** Optional resources directory */
  resourcesPath?: string;

  /** Optional REFERENCE.md for additional docs */
  referencePath?: string;

  /** List of all files in the skill */
  files: SkillFile[];
}

/**
 * Individual skill file
 */
export interface SkillFile {
  /** Relative path within skill directory */
  path: string;

  /** File type */
  type: 'markdown' | 'script' | 'resource' | 'config' | 'other';

  /** File size in bytes */
  size: number;

  /** Last modified timestamp */
  modified: string;
}

/**
 * Loaded skill instance
 */
export interface LoadedSkill {
  /** Skill metadata */
  metadata: SkillMetadata;

  /** Skill structure */
  structure: SkillStructure;

  /** SKILL.md content */
  instructions: string;

  /** Reference documentation (if available) */
  reference?: string;

  /** Script contents by filename */
  scripts: Map<string, string>;

  /** Resource contents by filename */
  resources: Map<string, Buffer | string>;

  /** Load timestamp */
  loadedAt: string;

  /** Token estimate for the skill */
  tokenEstimate: number;
}

/**
 * Skill loading options
 */
export interface SkillLoadOptions {
  /** Whether to load scripts */
  loadScripts?: boolean;

  /** Whether to load resources */
  loadResources?: boolean;

  /** Whether to include reference docs */
  includeReference?: boolean;

  /** Maximum token budget for skill content */
  maxTokens?: number;

  /** Custom base path for skill resolution */
  basePath?: string;
}

/**
 * Skill registry entry
 */
export interface SkillRegistryEntry {
  /** Skill ID */
  id: string;

  /** Display title */
  displayTitle: string;

  /** Latest version */
  latestVersion: string;

  /** Creation timestamp */
  createdAt: string;

  /** Last update timestamp */
  updatedAt: string;

  /** Source type */
  source: 'builtin' | 'custom' | 'marketplace';

  /** Skill path or URL */
  location: string;
}

/**
 * Skill execution context
 */
export interface SkillExecutionContext {
  /** Active skill */
  skill: LoadedSkill;

  /** Input parameters */
  parameters: Record<string, unknown>;

  /** Working directory */
  workingDir: string;

  /** Available tools */
  tools: string[];

  /** Execution timeout in ms */
  timeout?: number;
}

/**
 * Skill execution result
 */
export interface SkillExecutionResult {
  /** Whether execution succeeded */
  success: boolean;

  /** Result output */
  output?: string;

  /** Generated files */
  files?: GeneratedFile[];

  /** Error message if failed */
  error?: string;

  /** Execution duration in ms */
  durationMs: number;

  /** Token usage */
  usage?: {
    inputTokens: number;
    outputTokens: number;
  };
}

/**
 * File generated by skill execution
 */
export interface GeneratedFile {
  /** File name */
  name: string;

  /** File type */
  type: string;

  /** File content (base64 for binary) */
  content: string;

  /** Whether content is base64 encoded */
  isBase64: boolean;

  /** File size in bytes */
  size: number;
}

/**
 * Progressive disclosure stage
 */
export interface DisclosureStage {
  /** Stage name */
  name: string;

  /** Content to disclose at this stage */
  content: string;

  /** Token count for this stage */
  tokens: number;

  /** Whether this stage is required */
  required: boolean;

  /** Trigger for loading this stage */
  trigger?: 'immediate' | 'on-demand' | 'conditional';

  /** Condition for conditional loading */
  condition?: string;
}

/**
 * Skill container configuration
 */
export interface SkillContainerConfig {
  /** Skills to load in this container */
  skills: Array<{
    type: 'anthropic' | 'custom';
    skillId: string;
    version?: string;
  }>;

  /** Additional container settings */
  settings?: Record<string, unknown>;
}

/**
 * Skill validation result
 */
export interface SkillValidationResult {
  /** Whether skill is valid */
  valid: boolean;

  /** Validation errors */
  errors: string[];

  /** Validation warnings */
  warnings: string[];

  /** Metadata if successfully parsed */
  metadata?: SkillMetadata;
}
