/**
 * Common output formatting helpers
 */

const DIVIDER = '═'.repeat(60);
const SUB_DIVIDER = '─'.repeat(60);

export function formatExecutiveSummary(
  title: string,
  agentName: string,
  content: string,
  metadata: Record<string, string>
): string {
  const metaLines = Object.entries(metadata)
    .map(([key, value]) => `${key}: ${value}`)
    .join('\n');

  return `${DIVIDER}
${title}
${DIVIDER}

${metaLines}

${DIVIDER}

${content}

${DIVIDER}
Generated by ${agentName}
Enterprise AI Agent Suite
${DIVIDER}
`;
}

export function formatMarkdownReport(
  title: string,
  sections: Array<{ heading: string; content: string }>
): string {
  const body = sections
    .map(s => `## ${s.heading}\n\n${s.content}`)
    .join('\n\n---\n\n');

  return `# ${title}\n\n${body}`;
}

export function formatBulletList(items: string[]): string {
  return items.map(item => `  - ${item}`).join('\n');
}

export function formatNumberedList(items: string[]): string {
  return items.map((item, i) => `  ${i + 1}. ${item}`).join('\n');
}

export function wrapSection(label: string, content: string): string {
  return `${SUB_DIVIDER}\n${label}\n${SUB_DIVIDER}\n\n${content}\n`;
}
